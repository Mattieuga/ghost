drop policy if exists "cloud users can read their profile" on public.cloud_profiles;
create policy "cloud users can read their profile"
on public.cloud_profiles for select to authenticated
using ((select auth.uid()) = id);

drop policy if exists "cloud users can read visible workspaces" on public.cloud_workspaces;
create policy "cloud users can read visible workspaces"
on public.cloud_workspaces for select to authenticated
using (
  owner_id = (select auth.uid())
  or exists (
    select 1 from public.cloud_items as item
    where item.workspace_id = cloud_workspaces.id
      and private.cloud_has_role(item.id, 1, (select auth.uid()))
  )
);

drop policy if exists "cloud users can read visible items" on public.cloud_items;
create policy "cloud users can read visible items"
on public.cloud_items for select to authenticated
using (
  deleted_at is null
  and private.cloud_has_role(id, 1, (select auth.uid()))
);

drop policy if exists "cloud users can read relevant memberships" on public.cloud_memberships;
create policy "cloud users can read relevant memberships"
on public.cloud_memberships for select to authenticated
using (
  user_id = (select auth.uid())
  or private.cloud_has_role(item_id, 3, (select auth.uid()))
);

drop policy if exists "cloud users can read visible documents" on public.cloud_documents;
create policy "cloud users can read visible documents"
on public.cloud_documents for select to authenticated
using (private.cloud_has_role(document_id, 1, (select auth.uid())));

drop policy if exists "cloud users can load visible updates" on public.cloud_document_updates;
create policy "cloud users can load visible updates"
on public.cloud_document_updates for select to authenticated
using (private.cloud_has_role(document_id, 1, (select auth.uid())));

drop policy if exists "cloud editors can append updates" on public.cloud_document_updates;
create policy "cloud editors can append updates"
on public.cloud_document_updates for insert to authenticated
with check (
  author_id = (select auth.uid())
  and private.cloud_has_role(document_id, 2, (select auth.uid()))
);

drop policy if exists "cloud members can receive realtime" on realtime.messages;
create policy "cloud members can receive realtime"
on realtime.messages for select to authenticated
using (
  realtime.messages.extension = 'broadcast'
  and private.cloud_has_role(
    private.cloud_topic_document_id((select realtime.topic())),
    1,
    (select auth.uid())
  )
);

drop policy if exists "cloud editors can send realtime" on realtime.messages;
create policy "cloud editors can send realtime"
on realtime.messages for insert to authenticated
with check (
  realtime.messages.extension = 'broadcast'
  and private.cloud_has_role(
    private.cloud_topic_document_id((select realtime.topic())),
    2,
    (select auth.uid())
  )
);
